"""Generate ATT&CK coverage from the rules.

Writes coverage/attack-navigator-layer.json (open it at
https://mitre-attack.github.io/attack-navigator/) and coverage/COVERAGE.md.

    python tools/coverage.py          # regenerate both files
    python tools/coverage.py --check  # fail if they are out of date (used in CI)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from rules import ROOT, load_attack, load_rule, rule_files  # noqa: E402

COVERAGE_DIR = ROOT / "coverage"
LAYER_FILE = COVERAGE_DIR / "attack-navigator-layer.json"
MARKDOWN_FILE = COVERAGE_DIR / "COVERAGE.md"

TACTIC_ORDER = [
    "Reconnaissance", "ResourceDevelopment", "InitialAccess", "Execution", "Persistence",
    "PrivilegeEscalation", "DefenseEvasion", "CredentialAccess", "Discovery", "LateralMovement",
    "Collection", "CommandAndControl", "Exfiltration", "Impact",
]


def collect(paths: list[Path] | None = None) -> list[dict]:
    rules = []
    for path in paths or rule_files():
        rule = load_rule(path)
        rule["_path"] = path.relative_to(ROOT).as_posix()
        rules.append(rule)
    return sorted(rules, key=lambda r: r["name"])


def build_layer(rules: list[dict], attack: dict[str, dict]) -> dict:
    by_technique: dict[str, list[str]] = {}
    for rule in rules:
        for technique in rule["relevantTechniques"]:
            by_technique.setdefault(technique, []).append(rule["name"])
    max_score = max((len(v) for v in by_technique.values()), default=1)
    return {
        "name": "kql-detection-library coverage",
        "versions": {"layer": "4.5"},
        "domain": "enterprise-attack",
        "description": f"{len(rules)} KQL detections for Microsoft Sentinel / Defender XDR. Score = number of rules.",
        "techniques": [
            {
                "techniqueID": technique,
                "score": len(names),
                "comment": "; ".join(sorted(names)),
                "enabled": True,
                "showSubtechniques": True,
            }
            for technique, names in sorted(by_technique.items())
        ],
        "gradient": {"colors": ["#d6e9ff", "#1f6feb"], "minValue": 0, "maxValue": max_score},
        "legendItems": [],
        "hideDisabled": False,
        "showTacticRowBackground": False,
    }


def build_markdown(rules: list[dict], attack: dict[str, dict]) -> str:
    lines = [
        "# ATT&CK coverage",
        "",
        "Generated by `tools/coverage.py` - do not edit by hand.",
        "",
        f"**{len(rules)} rules** covering **{len({t for r in rules for t in r['relevantTechniques']})} techniques**.",
        "",
        "## By tactic",
        "",
        "| Tactic | Techniques | Rules |",
        "|---|---|---|",
    ]
    for tactic in TACTIC_ORDER:
        rules_here = [r for r in rules if tactic in r["tactics"]]
        if not rules_here:
            continue
        techniques = sorted({t for r in rules_here for t in r["relevantTechniques"] if tactic in attack[t]["tactics"]})
        lines.append(f"| {tactic} | {', '.join(techniques)} | {len(rules_here)} |")
    lines += [
        "",
        "## Rules",
        "",
        "| Rule | Severity | Techniques | Data | Runs every / looks back |",
        "|---|---|---|---|---|",
    ]
    for rule in rules:
        techniques = ", ".join(f"{t} {attack[t]['name']}" for t in rule["relevantTechniques"])
        tables = ", ".join(sorted({t for c in rule["requiredDataConnectors"] for t in c["dataTypes"]}))
        lines.append(
            f"| [{rule['name']}](../{rule['_path']}) | {rule['severity']} | {techniques} | {tables} "
            f"| {rule['queryFrequency']} / {rule['queryPeriod']} |"
        )
    return "\n".join(lines) + "\n"


def render() -> tuple[str, str]:
    attack = load_attack()
    rules = collect()
    return json.dumps(build_layer(rules, attack), indent=2) + "\n", build_markdown(rules, attack)


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    layer, markdown = render()
    if "--check" in argv:
        stale = [p for p, text in ((LAYER_FILE, layer), (MARKDOWN_FILE, markdown))
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)} (run python tools/coverage.py)")
        return 1 if stale else 0
    COVERAGE_DIR.mkdir(exist_ok=True)
    LAYER_FILE.write_text(layer, encoding="utf-8")
    MARKDOWN_FILE.write_text(markdown, encoding="utf-8")
    print(f"wrote {LAYER_FILE.relative_to(ROOT)} and {MARKDOWN_FILE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
